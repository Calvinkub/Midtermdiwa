"""## Task 7 (Bonus): Mini Modern Decoder Block
**Learning Objective:** Combine components into a modern transformer block.
**Structure:** `x = x + Attention(RMSNorm(x))`, then `x = x + SwiGLU(RMSNorm(x))`
"""

class ModernDecoderBlock(nn.Module):
    def __init__(self, dim, hidden_dim):
        super().__init__()
        self.norm1 = RMSNorm(dim)
        # Simplified attention using our causal_attention
        self.q_proj = nn.Linear(dim, dim)
        self.k_proj = nn.Linear(dim, dim)
        self.v_proj = nn.Linear(dim, dim)
        self.out_proj = nn.Linear(dim, dim)

        self.norm2 = RMSNorm(dim)
        self.ffn = SwiGLU(dim, hidden_dim)

    def forward(self, x):
        # 1. Attention block
        h = self.norm1(x)
        q, k, v = self.q_proj(h), self.k_proj(h), self.v_proj(h)
        attn_out = causal_attention(q, k, v)
        x = x + self.out_proj(attn_out)

        # 2. FFN block
        h = self.norm2(x)
        x = x + self.ffn(h)
        return x

