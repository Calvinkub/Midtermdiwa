"""## Task 4: Causal Attention
**Learning Objective:** Implement standard scaled dot-product attention with a causal mask.
**Formula:** $\text{Attention}(Q, K, V) = \text{softmax}\left(\frac{QK^T}{\sqrt{d}} + M\right)V$
**Expected Shapes:** $Q, K, V$: `(batch, seq, dim)`, Output `(batch, seq, dim)`
**Hints:**
1. Use `torch.tril(torch.ones(seq, seq))` to create a lower triangular mask.
2. Apply `torch.where` to set 0s to `-inf`.
"""

def causal_attention(q, k, v):
    # q, k, v: (batch, seq, dim)
    bs, seq, dim = q.shape

    # 1. Dot product
    scores = torch.matmul(q, k.transpose(-2, -1)) / math.sqrt(dim) # (batch, seq, seq)

    # 2. Causal mask
    mask = torch.tril(torch.ones(seq, seq)).view(1, seq, seq)
    scores = torch.where(mask == 0, torch.tensor(float('-inf')), scores)

    # 3. Softmax and value multiplication
    attn = F.softmax(scores, dim=-1)
    out = torch.matmul(attn, v) # (batch, seq, dim)
    return out

