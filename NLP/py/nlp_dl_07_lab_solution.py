"""## Task 6: KV Cache Memory Calculation
**Learning Objective:** Calculate KV Cache memory usage.
Calculate the memory (in MB) for: Batch size=4, Sequence length=2048, Head dimension=128, 32 layers, FP16 (2 bytes/param).
Compare MHA (32 heads) and GQA (8 heads).
**Formula:** `2 * batch * seq * n_kv_heads * head_dim * n_layers * bytes_per_param / (1024 * 1024)`
"""

def calc_kv_cache(batch, seq, n_kv_heads, head_dim, n_layers, bytes_per_param=2):
    # Calculate total elements: K and V (hence * 2) across all layers
    elements = 2 * batch * seq * n_kv_heads * head_dim * n_layers
    bytes_total = elements * bytes_per_param
    return bytes_total / (1024 * 1024)

