"""## Task 1: RMSNorm Forward
**Learning Objective:** Implement Root Mean Square Normalization.
**Formula:** $y = \frac{x}{\sqrt{\frac{1}{d} \sum_{i=1}^{d} x_i^2 + \epsilon}} \odot \gamma$\n
**Expected Shapes:** Input `(batch, seq, dim)`, Output `(batch, seq, dim)`
**Hints:**
1. Square the input (`x.to(torch.float32).pow(2)`) to avoid FP16 overflow.
2. Calculate the mean over the last dimension (`mean(dim=-1, keepdim=True)`)
3. Use `torch.rsqrt` for $1/\sqrt{\text{variance} + \epsilon}$
4. Cast back to the original dtype (`.to(x.dtype)`) before multiplying by `self.weight`.
"""

class RMSNorm(nn.Module):
    def __init__(self, dim, eps=1e-6):
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim)) # Shape: (dim,)

    def forward(self, x):
        # x: (batch_size, seq_len, dim)
        # 1. Calculate variance in float32 for numerical stability
        variance = x.to(torch.float32).pow(2).mean(dim=-1, keepdim=True) # Shape: (batch_size, seq_len, 1)
        # 2. Normalize and apply learnable weight
        x_norm = x * torch.rsqrt(variance + self.eps).to(x.dtype) # Shape: (batch_size, seq_len, dim)
        return self.weight * x_norm # Shape: (batch_size, seq_len, dim)

