"""## Task 10: Activation Patching / Function Vector
**Learning Objective:** Extract an activation vector from a few-shot prompt context and add it to the residual stream of a zero-shot prompt to observe the logit probability spike.
**Hints:**
1. We will use a pre-trained model and hook into its layers, or simply use the `output_hidden_states=True` flag to get hidden states.
2. We extract the hidden state of the last token from a few-shot prompt (e.g., translation or capitalization).
3. For the zero-shot prompt, we manually add this vector to the embeddings before passing it through the rest of the model, or use a hook to add it at a specific layer.
"""

# Task: Capitalization function vector
few_shot = "cat -> CAT\ndog -> DOG\napple -> APPLE"
zero_shot = "bird ->"

# 1. Get hidden states from few-shot prompt
inputs_few = tokenizer(few_shot, return_tensors="pt")
with torch.no_grad():
    outputs_few = model(**inputs_few, output_hidden_states=True)
    # Extract the vector at layer 6, last token
    layer_idx = 6
    func_vector = outputs_few.hidden_states[layer_idx + 1][0, -1, :].clone()  # Shape: (768,)

# 2. Define a hook to patch the vector into the zero-shot forward pass
def patching_hook(module, input, output):
    # In newer transformers, GPT-2 block returns a Tensor directly; in older, a tuple.
    if isinstance(output, tuple):
        hidden = output[0].clone()
        hidden[..., -1, :] += func_vector  # patch last token position
        return (hidden,) + output[1:]
    else:
        # output is a plain Tensor: (seq_len, hidden_size) or (batch, seq_len, hidden_size)
        hidden = output.clone()
        hidden[..., -1, :] += func_vector
        return hidden

# 3. Run zero-shot WITH patching
inputs_zero = tokenizer(zero_shot, return_tensors="pt")

# Register hook at layer 6
handle = model.transformer.h[layer_idx].register_forward_hook(patching_hook)

with torch.no_grad():
    outputs_patched = model(**inputs_zero)

# Remove hook
handle.remove()

# 4. Compare with unpatched
with torch.no_grad():
    outputs_unpatched = model(**inputs_zero)

patched_logits = outputs_patched.logits[0, -1, :]
unpatched_logits = outputs_unpatched.logits[0, -1, :]

print("Unpatched top predictions for 'bird':")
top_unpatched = torch.topk(F.softmax(unpatched_logits, dim=-1), 3)
for i in range(3):
    print(f"- {tokenizer.decode(top_unpatched.indices[i])}: {top_unpatched.values[i].item():.4f}")

print("\nPatched (with capitalization vector) top predictions for 'bird':")
top_patched = torch.topk(F.softmax(patched_logits, dim=-1), 3)
for i in range(3):
    print(f"- {tokenizer.decode(top_patched.indices[i])}: {top_patched.values[i].item():.4f}")

