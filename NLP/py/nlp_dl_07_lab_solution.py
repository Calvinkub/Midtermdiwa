"""## Task 5: Grouped-Query Attention (GQA) `repeat_kv`
**Learning Objective:** Implement the KV repetition step for GQA.
**Expected Shapes:** Input `(batch, seq, n_kv_heads, head_dim)`, Output `(batch, seq, n_kv_heads * n_rep, head_dim)`
**Hints:** Expand a new dimension after `n_kv_heads`, expand to `n_rep`, and then reshape.
"""

def repeat_kv(x, n_rep):
    # x: (batch, seq, n_kv_heads, head_dim)
    bs, slen, n_kv_heads, head_dim = x.shape
    if n_rep == 1:
        return x

    # 1. Add dimension: (batch, seq, n_kv_heads, 1, head_dim)
    # 2. Expand: (batch, seq, n_kv_heads, n_rep, head_dim)
    # 3. Reshape: (batch, seq, n_kv_heads * n_rep, head_dim)
    return x.unsqueeze(3).expand(bs, slen, n_kv_heads, n_rep, head_dim).reshape(bs, slen, -1, head_dim)

