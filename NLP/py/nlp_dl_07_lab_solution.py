"""## Task 8: Manual Generation with KV Cache
**Learning Objective:** Implement a manual autoregressive loop using `past_key_values`.
**Hints:**
1. In the loop, pass `past_key_values` to the model.
2. The model returns `logits` and the updated `past_key_values`.
3. Use the latest logit (index `[:, -1, :]`) to get the next token using `argmax`.
4. Append the next token to your sequence. For the next step, you only need to pass the *new* token to the model, along with the `past_key_values`!
"""

model_id = "gpt2"
tokenizer = GPT2Tokenizer.from_pretrained(model_id)
model = GPT2LMHeadModel.from_pretrained(model_id)
model.eval()

prompt = "The capital of France is"
input_ids = tokenizer(prompt, return_tensors="pt").input_ids

generated_ids = input_ids.clone()
past_kv = None
next_input = input_ids

print("Starting generation...")
with torch.no_grad():
    for _ in range(5): # Generate 5 tokens
        # Pass input and past_kv
        outputs = model(next_input, past_key_values=past_kv)

        # Get next token from the last logit
        next_token_logits = outputs.logits[:, -1, :]
        next_token = torch.argmax(next_token_logits, dim=-1, keepdim=True)

        # Update past_kv and sequence
        past_kv = outputs.past_key_values
        generated_ids = torch.cat([generated_ids, next_token], dim=-1)

        # Next input is ONLY the newly generated token
        next_input = next_token

print("Generated:", tokenizer.decode(generated_ids[0]))

"""## Task 9: CLM Loss Implementation
**Learning Objective:** Manually calculate the causal language modeling loss by shifting logits and labels.
**Hints:**
1. Logits should predict the *next* token. So `shift_logits` takes all but the last prediction.
2. Labels should be the *actual* next token. So `shift_labels` takes all but the first token.
3. Flatten both before passing to `CrossEntropyLoss`.
"""

