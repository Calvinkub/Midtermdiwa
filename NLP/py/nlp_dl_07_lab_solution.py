"""## Task 2: SwiGLU Forward
**Learning Objective:** Implement SwiGLU activation.
**Formula:** $\text{SwiGLU}(x, W_1, W_2, W_3) = (\text{SiLU}(xW_1) \odot xW_3)W_2$
**Expected Shapes:** Input `(batch, seq, in_dim)`, Output `(batch, seq, in_dim)`
**Parameter Budget:** $W_1: \text{in} \times \text{hidden}$, $W_3: \text{in} \times \text{hidden}$, $W_2: \text{hidden} \times \text{in}$. Total parameters = $3 \times \text{in} \times \text{hidden}$.
**Hints:** Use `F.silu` for the Swish activation.\n
<br>*(Note: we follow LLaMA's w1/w3/w2 naming; the slide uses Shazeer's W1/W2/W3)*
"""

class SwiGLU(nn.Module):
    def __init__(self, in_dim, hidden_dim):
        super().__init__()
        self.w1 = nn.Linear(in_dim, hidden_dim, bias=False)
        self.w3 = nn.Linear(in_dim, hidden_dim, bias=False)
        self.w2 = nn.Linear(hidden_dim, in_dim, bias=False)

    def forward(self, x):
        # x: (batch_size, seq_len, in_dim)
        gate = F.silu(self.w1(x)) # (batch_size, seq_len, hidden_dim)
        val = self.w3(x)          # (batch_size, seq_len, hidden_dim)
        hidden = gate * val       # (batch_size, seq_len, hidden_dim)
        return self.w2(hidden)    # (batch_size, seq_len, in_dim)

