"""## Task 3: Apply RoPE
**Learning Objective:** Apply precomputed RoPE frequencies to queries and keys.
**Expected Shapes:** Input `xq, xk: (batch, seq, heads, dim)`, Output `(batch, seq, heads, dim)`
**Hints:**
1. Reshape `xq` and `xk` into complex representations using `torch.view_as_complex`. The last dim becomes `dim // 2`.
2. Multiply by `freqs_cis`.
3. Use `torch.view_as_real` and `flatten(3)` to restore the original shape.
"""

def precompute_freqs_cis(dim: int, end: int, theta: float = 10000.0):
    freqs = 1.0 / (theta ** (torch.arange(0, dim, 2)[: (dim // 2)].float() / dim))
    t = torch.arange(end, device=freqs.device, dtype=torch.float32)
    freqs = torch.outer(t, freqs)
    return torch.polar(torch.ones_like(freqs), freqs)

def apply_rotary_emb(xq, xk, freqs_cis):
    # xq, xk: (batch, seq, heads, dim)
    # 1. Convert to complex
    xq_ = torch.view_as_complex(xq.float().reshape(*xq.shape[:-1], -1, 2)) # (batch, seq, heads, dim//2)
    xk_ = torch.view_as_complex(xk.float().reshape(*xk.shape[:-1], -1, 2)) # (batch, seq, heads, dim//2)

    # 2. Reshape freqs_cis to broadcast: (1, seq, 1, dim//2)
    freqs_cis = freqs_cis.unsqueeze(0).unsqueeze(2)

    # 3. Multiply and convert back
    xq_out = torch.view_as_real(xq_ * freqs_cis).flatten(3) # (batch, seq, heads, dim)
    xk_out = torch.view_as_real(xk_ * freqs_cis).flatten(3) # (batch, seq, heads, dim)

    return xq_out.type_as(xq), xk_out.type_as(xk)

